"""A generative simulator standing in for a model family.

Purpose, precisely: Phase 0 exists to validate the pipeline end to end --
tokenization, adaptation, output parsing, memory behaviour, result schema
(protocol section 15) -- and the *analysis* half of that has to be checkable
without waiting on five fine-tuning runs. The simulator produces prediction
matrices whose dependence structure is known by construction, so the metrics
in `hg.metrics` can be verified against a ground truth before they are pointed
at real models.

It is a test instrument, not evidence. Nothing it produces is a result about
LLMs. It is registered as a backend so the exact same runner, schema and
analysis code path is exercised.

The generative model
--------------------
For item i and ensemble member j:

    logit P(E_ij = 1) = alpha_j            family skill (lower = better)
                      + u_i               item difficulty, shared by everyone
                      + b_lineage(i, L_j) bias shared within a model lineage
                      + b_data(i, S_j)    bias shared by a training slice
                      + core_strength * core_i

The four nuisance terms are what the experiment is designed to separate:

* `u_i` is ordinary correlated difficulty. It inflates consensus-wrong rates
  even under perfect independence of everything else -- which is exactly why
  the naive independence null prod_j p_j is not a credible baseline (section 9).
* `b_lineage` is shared *representational* error. Members of one family share
  it, so it survives seed variation and dissolves when families differ. This
  is the term `Delta_div` is meant to detect.
* `b_data` is shared *information* error, keyed on the training slice. Shared
  slices share it; disjoint slices do not. This is what HD and DS decompose.
* `core_i` marks an information-limited core: items every family gets wrong
  regardless of lineage or data. Set `core_rate=0` to simulate decision-gate
  outcome A (clean residual vanishes) and `core_rate>0` to simulate outcome C
  (a stable clean shared residual survives DD). Both are worth simulating
  before the real run, because the analysis has to be able to tell them apart.

Randomness is derived by hashing `(seed, kind, keys...)`, so a member's
predictions depend on neither evaluation order nor how many members ran. That
is what makes the "diverse" conditions honestly independent rather than
correlated through a shared RNG stream.
"""

from __future__ import annotations

import hashlib
import math
import struct
from dataclasses import dataclass
from typing import Any, Mapping, Sequence

from .base import (
    Backend,
    GenerationSettings,
    InferenceItem,
    Prediction,
    register_backend,
)

# Latent item fields the simulator reads out of `InferenceItem.meta`. They are
# generated by `hg.tasks.synthetic` and travel with the dataset, so every
# member sees the same item difficulty.
META_DIFFICULTY = "sim_difficulty"
META_CORE = "sim_core"
META_TRUE_LABEL = "sim_true_label"


def _u64(seed: int, kind: str, *keys: Any) -> int:
    payload = "\x1f".join([kind, *(str(k) for k in keys)]).encode("utf-8")
    digest = hashlib.blake2b(payload, digest_size=8, key=struct.pack("<q", seed)).digest()
    return int.from_bytes(digest, "little")


def _uniform(seed: int, kind: str, *keys: Any) -> float:
    """Deterministic U(0, 1) keyed on the given coordinates."""
    return _u64(seed, kind, *keys) / 2.0**64


def _normal(seed: int, kind: str, *keys: Any) -> float:
    """Deterministic standard normal via Box-Muller on two keyed uniforms."""
    u1 = max(_uniform(seed, kind + ":n1", *keys), 1e-12)
    u2 = _uniform(seed, kind + ":n2", *keys)
    return math.sqrt(-2.0 * math.log(u1)) * math.cos(2.0 * math.pi * u2)


def _sigmoid(z: float) -> float:
    if z >= 0:
        return 1.0 / (1.0 + math.exp(-z))
    e = math.exp(z)
    return e / (1.0 + e)


@dataclass(slots=True)
class SimulatorParams:
    """Per-member simulator configuration, read from `ModelConfig.options`."""

    # alpha_j: family skill on the error logit. Lower is a stronger model.
    skill: float = -1.5
    # Scale of the lineage-shared error bias b_lineage.
    lineage_bias: float = 1.6
    # Scale of the training-slice-shared error bias b_data.
    data_bias: float = 1.0
    # Extra error logit on core items, applied to every member.
    core_strength: float = 6.0
    # Probability the model emits output the canonicalizer cannot read.
    parse_failure_rate: float = 0.0
    # Width of the reported confidence around the true error probability.
    confidence_noise: float = 0.05
    # Emit a representation embedding of this width (0 disables).
    embedding_dim: int = 0

    @classmethod
    def from_options(cls, options: Mapping[str, Any]) -> "SimulatorParams":
        known = {f: options[f] for f in cls.__slots__ if f in options}  # type: ignore[attr-defined]
        unknown = set(options) - set(cls.__slots__) - {"lineage"}  # type: ignore[attr-defined]
        if unknown:
            raise ValueError(f"unknown simulator options: {sorted(unknown)}")
        return cls(**known)


@register_backend("simulator")
class SimulatorBackend:
    """Backend that samples errors from the model above.

    Constructed by the runner with the member's identity, so `lineage` and
    `train_split` -- not the member name -- decide which nuisance terms are
    shared. Two members with the same lineage share `b_lineage` even if they
    are called different things, which is the whole point of section 3's
    warning about counting variants of one foundation model as diversity.
    """

    name = "simulator"

    def __init__(
        self,
        *,
        lineage: str,
        train_split: str = "shared",
        adapter_seed: int = 0,
        world_seed: int = 0,
        params: SimulatorParams | Mapping[str, Any] | None = None,
        checkpoint: str = "simulator",
    ) -> None:
        self.lineage = lineage
        self.train_split = train_split
        self.adapter_seed = int(adapter_seed)
        self.world_seed = int(world_seed)
        self.checkpoint = checkpoint
        if params is None:
            self.params = SimulatorParams()
        elif isinstance(params, SimulatorParams):
            self.params = params
        else:
            self.params = SimulatorParams.from_options(params)
        self._loaded = False

    def load(self) -> None:
        self._loaded = True

    def unload(self) -> None:
        self._loaded = False

    # -- the generative model -------------------------------------------
    def error_probability(self, item: InferenceItem) -> float:
        p = self.params
        meta = item.meta
        difficulty = float(meta.get(META_DIFFICULTY, 0.0))
        core = bool(meta.get(META_CORE, False))

        # Shared within a lineage: same key for every member of that lineage.
        b_lineage = p.lineage_bias * _normal(self.world_seed, "lineage", self.lineage, item.item_id)
        # Shared within a training slice.
        b_data = p.data_bias * _normal(self.world_seed, "data", self.train_split, item.item_id)
        # Idiosyncratic seed/order variation, unique to this member.
        b_seed = 0.35 * _normal(
            self.world_seed, "seed", self.lineage, self.train_split, self.adapter_seed, item.item_id
        )

        z = p.skill + difficulty + b_lineage + b_data + b_seed
        if core:
            z += p.core_strength
        return _sigmoid(z)

    def predict(
        self, items: Sequence[InferenceItem], settings: GenerationSettings
    ) -> list[Prediction]:
        if not self._loaded:
            self.load()
        out: list[Prediction] = []
        p = self.params
        for item in items:
            labels = list(item.labels)
            true_label = str(item.meta.get(META_TRUE_LABEL, labels[0]))
            p_err = self.error_probability(item)

            draw_key = (self.lineage, self.train_split, self.adapter_seed, item.item_id)
            errs = _uniform(self.world_seed, "err", *draw_key, settings.seed)
            is_error = errs < p_err

            if is_error:
                wrong = [l for l in labels if l != true_label] or labels
                idx = _u64(self.world_seed, "wrong", *draw_key) % len(wrong)
                label = wrong[idx]
            else:
                label = true_label

            # Confidence reports P(chosen label), noisily, the way a real
            # model's calibration is imperfect. Routing strategies must not
            # assume it is exact.
            base_conf = 1.0 - p_err if not is_error else p_err
            noise = p.confidence_noise * _normal(self.world_seed, "conf", *draw_key)
            confidence = min(max(base_conf + noise, 1e-4), 1.0 - 1e-4)

            probs = _distribute(labels, label, confidence)
            logprob = math.log(confidence)

            parse_ok = True
            raw = label
            if p.parse_failure_rate > 0 and _uniform(
                self.world_seed, "parse", *draw_key
            ) < p.parse_failure_rate:
                parse_ok = False
                raw = "I'd rather not categorise this."
                label = None
                probs = None
                logprob = None
                confidence = None

            embedding = None
            if p.embedding_dim > 0:
                embedding = [
                    _normal(self.world_seed, "emb", self.lineage, item.item_id, k)
                    for k in range(p.embedding_dim)
                ]

            out.append(
                Prediction(
                    item_id=item.item_id,
                    label=label,
                    raw_output=raw,
                    parse_ok=parse_ok,
                    confidence=confidence,
                    probs=probs,
                    logprob=logprob,
                    embedding=embedding,
                )
            )
        return out


def _distribute(labels: Sequence[str], chosen: str, confidence: float) -> dict[str, float]:
    """Put `confidence` on `chosen` and spread the rest evenly."""
    rest = [l for l in labels if l != chosen]
    if not rest:
        return {chosen: 1.0}
    share = (1.0 - confidence) / len(rest)
    probs = {l: share for l in rest}
    probs[chosen] = confidence
    return {l: probs[l] for l in labels}
