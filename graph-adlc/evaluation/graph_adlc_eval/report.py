"""Score predictions against the oracle and write JSON/CSV/Markdown results.

    python -m graph_adlc_eval.report --predictions evaluation/out/predictions.jsonl \
        --oracle evaluation/oracle --out evaluation/out
"""

from __future__ import annotations

import argparse
import csv
import json
from collections import defaultdict
from pathlib import Path
from typing import Any

from .dataset import load_dataset
from .scoring import load_oracle, load_predictions, pruning_audit, score

METHODS = ["A", "A2", "B", "C"]
PRIMARY = ["A", "B", "C"]


def _f(v: Any) -> str:
    return "N/A" if v is None else (f"{v:.3f}" if isinstance(v, float) else str(v))


def _write_csv(path: Path, rows: list[dict[str, Any]]) -> None:
    cols = ["scenario_id", "method", "family", "gold", "predicted", "tp", "fp", "fn", "precision", "recall", "f1",
            "unknown_predicted", "unknown_not_predicted", "t_tp", "t_fp", "t_fn", "t_precision", "t_recall",
            "missed", "false_positives"]
    with open(path, "w", newline="", encoding="utf-8") as fh:
        w = csv.DictWriter(fh, fieldnames=cols, extrasaction="ignore", lineterminator="\n")
        w.writeheader()
        for r in rows:
            w.writerow({**r, "missed": "; ".join(r["missed"]), "false_positives": "; ".join(r["false_positives"]),
                        **{k: _f(r[k]) for k in ("precision", "recall", "f1", "t_precision", "t_recall")}})


def markdown(res: dict[str, Any], audit: list[dict[str, Any]], costs: list[dict[str, Any]], label: str,
             excluded: list[dict[str, Any]], post_hoc: dict[str, Any]) -> str:
    T = res["totals"]
    L = [f"# Generated evaluation report — oracle {label}", "",
         "Generated by `graph_adlc_eval.report`. Do not edit by hand.", "",
         "## Pair-level (target, obligation), micro over judged pairs", "",
         "| Method | Gold | Pred | TP | FP | FN | Precision | Recall | F1 | Macro recall (non-empty) | Critical missed / gold |",
         "|---|---:|---:|---:|---:|---:|---:|---:|---:|---:|---:|"]
    for m in METHODS:
        t = T[m]
        L.append(f"| {m} | {t['gold']} | {t['predicted']} | {t['tp']} | {t['fp']} | {t['fn']} | {_f(t['micro_precision'])} | "
                 f"{_f(t['micro_recall'])} | {_f(t['micro_f1'])} | {_f(t['macro_recall_nonempty_gold'])} | "
                 f"{t['critical_missed']} / {t['critical_gold']} |")
    L += ["", "## Target-level (obligation type ignored)", "",
          "| Method | TP | FP | FN | Precision | Recall | F1 | Macro recall (non-empty) |", "|---|---:|---:|---:|---:|---:|---:|---:|"]
    for m in METHODS:
        t = T[m]
        L.append(f"| {m} | {t['t_tp']} | {t['t_fp']} | {t['t_fn']} | {_f(t['t_micro_precision'])} | {_f(t['t_micro_recall'])} | "
                 f"{_f(t['t_micro_f1'])} | {_f(t['t_macro_recall_nonempty_gold'])} |")
    L += ["", "## Unknown-label sensitivity (pair level)", "",
          "| Method | Unknown predicted | Unknown not predicted | Best-case P / R | Worst-case P / R |", "|---|---:|---:|---|---|"]
    for m in METHODS:
        t = T[m]
        L.append(f"| {m} | {t['unknown_predicted']} | {t['unknown_not_predicted']} | {_f(t['best_case']['precision'])} / "
                 f"{_f(t['best_case']['recall'])} | {_f(t['worst_case']['precision'])} / {_f(t['worst_case']['recall'])} |")
    L += ["", "## Exploratory, post hoc (NOT pre-registered): pairs with obligation rerun_test removed from gold and predictions", "",
          "Shows how much the result depends on the labeling rule 'tests executing changed code must be re-run'.", "",
          "| Method | TP | FP | FN | Precision | Recall |", "|---|---:|---:|---:|---:|---:|"]
    for m in METHODS:
        t = post_hoc["totals"][m]
        L.append(f"| {m} | {t['tp']} | {t['fp']} | {t['fn']} | {_f(t['micro_precision'])} | {_f(t['micro_recall'])} |")
    L += ["", "## Negative (empty-gold) cases", "", "| Method | Negative cases | With false alarm | False-alarm pairs |",
          "|---|---:|---:|---:|"]
    for m in METHODS:
        n = T[m]["negative_cases"]
        L.append(f"| {m} | {n['cases']} | {n['cases_with_false_alarm']} | {n['false_alarm_pairs']} |")
    L += ["", "## By change family (pair level)", "", "| Family | " + " | ".join(f"{m} P / R" for m in METHODS) + " |",
          "|---|" + "---|" * len(METHODS)]
    for fam in sorted(T["B"]["by_family"]):
        L.append(f"| {fam} | " + " | ".join(f"{_f(T[m]['by_family'][fam]['precision'])} / {_f(T[m]['by_family'][fam]['recall'])}"
                                              for m in METHODS) + " |")
    L += ["", "## Critical misses", ""]
    for m in METHODS:
        L.append(f"- **{m}**: " + (", ".join(T[m]["critical_missed_list"]) or "none"))
    L += ["", "## Pruning audit (B vs C)", "", "| Scenario | Evidence passed | Pruned boundaries | Removed pairs (oracle label) | Pruning misses |",
          "|---|---|---|---|---:|"]
    for a in audit:
        pb = "; ".join(f"{p['provider_id']}->{p['consumer_id']} via {p['edge_id']} by {p['evidence_id']} {p['contracts']}"
                       for p in a["pruned_boundaries"]) or "none"
        ev = "; ".join(f"{e['evidence_id']} {e['result']} {e['spec_revs']}" for e in a["setup_evidence"]) or "none"
        rm = "; ".join(f"{r['target_id']}:{r['obligation']} ({r['oracle']})" for r in a["removed"]) or "none"
        L.append(f"| {a['scenario_id']} | {ev} | {pb} | {rm} | {len(a['pruning_misses'])} |")
    L += ["", "## Per scenario (pair level: TP/FP/FN)", "", "| Scenario | Family | Gold | " + " | ".join(METHODS) + " |",
          "|---|---|---:|" + "---|" * len(METHODS)]
    rows = defaultdict(dict)
    for r in res["per_scenario"]:
        rows[r["scenario_id"]][r["method"]] = r
    for sid in sorted(rows):
        r0 = rows[sid]["B"]
        L.append(f"| {sid} | {r0['family']} | {r0['gold']} | " +
                 " | ".join(f"{rows[sid][m]['tp']}/{rows[sid][m]['fp']}/{rows[sid][m]['fn']}" for m in METHODS) + " |")
    L += ["", "## Misses and false positives by scenario", ""]
    for sid in sorted(rows):
        L.append(f"### {sid}")
        for m in METHODS:
            r = rows[sid][m]
            L.append(f"- {m}: missed [{', '.join(r['missed'])}]; FP [{', '.join(r['false_positives'])}]")
        L.append("")
    L += ["## Cost proxies (sums over 24 scenarios; machine-measured, not human effort)", "",
          "| Method | Predicted pairs | Predicted targets | Context sections/nodes | Context chars | Evidence records used | Provisional pairs | Low-confidence pairs |",
          "|---|---:|---:|---:|---:|---:|---:|---:|"]
    for m in METHODS:
        cs = [c for c in costs if c["method"] == m]
        L.append(f"| {m} | {sum(c['predicted_pairs'] for c in cs)} | {sum(c['predicted_targets'] for c in cs)} | "
                 f"{sum(c['context_sections'] for c in cs)} | {sum(c.get('context_chars', 0) for c in cs) or 'n/a'} | "
                 f"{sum(c['evidence_records_used'] for c in cs)} | {sum(c.get('provisional_pairs', 0) for c in cs)} | "
                 f"{sum(c.get('low_confidence_pairs', 0) for c in cs)} |")
    ex = defaultdict(int)
    for e in excluded:
        ex[(e["method"], e["excluded_reason"])] += 1
    L += ["", "## Excluded prediction records", ""]
    L += [f"- {m}: {n} x {why}" for (m, why), n in sorted(ex.items())] or ["- none"]
    return "\n".join(L) + "\n"


def main(argv: list[str] | None = None) -> int:
    ap = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    ap.add_argument("--predictions", default="evaluation/out/predictions.jsonl")
    ap.add_argument("--oracle", default="evaluation/oracle")
    ap.add_argument("--dataset", default="evaluation/scenarios")
    ap.add_argument("--out", default="evaluation/out")
    args = ap.parse_args(argv)
    out, oracle_dir = Path(args.out), Path(args.oracle)
    preds = load_predictions(Path(args.predictions))
    excluded = load_predictions(Path(args.predictions).with_name("excluded_predictions.jsonl"))
    costs = load_predictions(Path(args.predictions).with_name("costs.jsonl"))
    scen = [{"id": s.id, "family": s.family, "tags": s.tags} for s in load_dataset(Path(args.dataset))]
    versions = ["v1"] + (["v1.1"] if (oracle_dir / "review_v1_1.jsonl").exists() else [])
    for v in versions:
        oracle = load_oracle(oracle_dir, v)
        missing = [s["id"] for s in scen if s["id"] not in oracle]
        if missing:
            raise SystemExit(f"oracle {v} missing scenarios {missing}")
        res = score(preds, oracle, scen, METHODS)
        no_tests = {k: {**o, "necessary_checks": [c for c in o["necessary_checks"] if c["obligation"] != "rerun_test"],
                        "unknown_checks": [c for c in o["unknown_checks"] if c["obligation"] != "rerun_test"]}
                    for k, o in oracle.items()}
        post_hoc = score([p for p in preds if p["obligation"] != "rerun_test"], no_tests, scen, METHODS)
        audit = pruning_audit(preds, out / "raw", oracle, [s["id"] for s in scen])
        tag = v.replace(".", "_")
        (out / f"metrics_{tag}.json").write_text(json.dumps({"oracle_version": v, **res, "pruning_audit": audit,
                                                             "post_hoc_without_rerun_test": post_hoc["totals"]},
                                                            indent=2, sort_keys=True) + "\n", encoding="utf-8")
        _write_csv(out / f"per_scenario_{tag}.csv", res["per_scenario"])
        (out / f"report_{tag}.md").write_text(markdown(res, audit, costs, v, excluded, post_hoc), encoding="utf-8")
        t = res["totals"]
        print(f"[{v}] " + "  ".join(f"{m}: P={_f(t[m]['micro_precision'])} R={_f(t[m]['micro_recall'])}" for m in METHODS))
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
