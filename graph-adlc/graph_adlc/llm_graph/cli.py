"""gadlc-llm: opt-in LLM graph-maintenance commands (v0.3).

A *bundle file* names the sources supplied for one step:

    {"project": "toolshare", "root": "path/to/docs",
     "files": [{"path": "spec/requirements.v2.md", "logical_path": "spec/requirements.md",
                "type": "requirements", "version": "draft-2"}],
     "git": {"repo": "path/to/repo", "name": "toolshare", "commit": "HEAD", "diff_from": "HEAD~1"}}

Typical flow (nothing is committed before ``decide``):

    gadlc-llm propose   --db g.sqlite --bundle b.json --event "requirements draft 2" --provider anthropic --model <id>
    gadlc-llm show      --db g.sqlite --bundle b.json P-0001
    gadlc-llm decide    --db g.sqlite --bundle b.json P-0001 --reviewer alice --accept op-1,op-2 --defer op-3 --reject op-4
    gadlc-llm challenge --db g.sqlite --bundle b.json --node CON-X --aspect contract
    gadlc-llm export-spec --db g.sqlite --out spec.md
"""

from __future__ import annotations

import argparse
import json
import sys
from pathlib import Path
from typing import Any

from ..core import GraphADLC
from ..validation import RevisionConflict, ValidationError
from .ledger import Ledger
from .maintenance import MaintenanceLoop
from .model_adapter import AnthropicMessagesClient, LLMNotConfigured, LLMProposer, OpenAIChatClient, ScriptedClient
from .projection import export_spec_markdown
from .proposal import parse_proposal
from .review import Decision, NeedsRegeneration, ReviewError, apply_review, decisions_from_json, render_review
from .source import SourceBundle, git_diff, load_file_source, load_git_sources
from .validation import validate_proposal


def load_bundle(path: str) -> SourceBundle:
    spec = json.loads(Path(path).read_text())
    base = Path(path).parent
    root = (base / spec.get("root", ".")).resolve()
    docs = [load_file_source(root, spec["project"], f["path"], f["type"], f["version"], f.get("logical_path"))
            for f in spec.get("files", [])]
    diffs = []
    if spec.get("git"):
        g = spec["git"]
        repo = (base / g["repo"]).resolve()
        docs += load_git_sources(repo, g.get("name", repo.name), spec["project"], g.get("commit", "HEAD"), g.get("paths"))
        if g.get("diff_from"):
            diffs.append(git_diff(repo, g.get("name", repo.name), g["diff_from"], g.get("commit", "HEAD")))
    return SourceBundle(project=spec["project"], documents=docs, diffs=diffs)


def _client(a: argparse.Namespace) -> Any:
    if a.provider == "scripted":
        data = json.loads(Path(a.scripted).read_text())
        return ScriptedClient(data.get("responses", data), label=Path(a.scripted).name)
    import os
    model = a.model or os.environ.get("GADLC_LLM_MODEL", "")
    if a.provider == "openai":
        return OpenAIChatClient(model=model, api_key_env=a.api_key_env or "OPENAI_API_KEY")
    return AnthropicMessagesClient(model=model, api_key_env=a.api_key_env or "ANTHROPIC_API_KEY")


def _reload(app: GraphADLC, ledger: Ledger, pid: str, bundle: SourceBundle) -> tuple[Any, dict[str, Any]]:
    row = ledger.proposal(pid)
    raw = row["proposal"]
    prop = parse_proposal(raw, raw["proposal_id"], raw["base_graph_revision"], raw.get("origin"))
    prop.operations = [o for o in prop.operations if not o.op_id.startswith("auto-")]  # regenerated by validation
    prop, report = validate_proposal(app, prop, bundle, None, ledger)
    return prop, report


def main(argv: list[str] | None = None) -> int:
    ap = argparse.ArgumentParser(prog="gadlc-llm", description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    ap.add_argument("--db", required=True)
    sub = ap.add_subparsers(dest="cmd", required=True)
    p = sub.add_parser("propose", help="ask the model for a proposal; validate and store it (no commit)")
    p.add_argument("--bundle", required=True)
    p.add_argument("--event", required=True, help="short description of what changed")
    p.add_argument("--provider", choices=("anthropic", "openai", "scripted"), required=True)
    p.add_argument("--model", help="model id (required for --provider anthropic)")
    p.add_argument("--api-key-env", default=None, help="env var holding the key (default per provider)")
    p.add_argument("--scripted", help="JSON file of scripted responses (fake; for tests/demos)")
    p.add_argument("--call-key", default="cli/propose")
    s = sub.add_parser("show", help="re-validate a stored proposal and print the review view")
    s.add_argument("--bundle", required=True)
    s.add_argument("proposal_id")
    d = sub.add_parser("decide", help="record accept/reject/defer decisions and commit accepted ops")
    d.add_argument("--bundle", required=True)
    d.add_argument("proposal_id")
    d.add_argument("--reviewer", required=True)
    d.add_argument("--accept", default="")
    d.add_argument("--reject", default="")
    d.add_argument("--defer", default="")
    d.add_argument("--ack", default="", help="quarantined op ids whose findings the reviewer explicitly accepts")
    d.add_argument("--rationale", default="")
    d.add_argument("--decisions", help="JSON list of {op_id, decision, rationale, acknowledge}")
    c = sub.add_parser("challenge", help="look for missing dependencies around an intended change")
    c.add_argument("--bundle", required=True)
    c.add_argument("--node", required=True)
    c.add_argument("--aspect", required=True)
    e = sub.add_parser("export-spec", help="write the spec-only Markdown projection")
    e.add_argument("--out", required=True)
    e.add_argument("--title", default="Specification")
    sub.add_parser("ledger", help="list proposals and decisions")
    a = ap.parse_args(argv)

    app = GraphADLC(a.db)
    if not app.store.initialized():
        app.seed_graph({"graph_revision": 1, "nodes": [], "edges": []})
    try:
        if a.cmd == "propose":
            try:
                loop = MaintenanceLoop(app, LLMProposer(_client(a)))
                st = loop.propose(load_bundle(a.bundle), {"kind": "source_revision", "summary": a.event},
                                  call_key=a.call_key)
            except LLMNotConfigured as ex:
                print(f"not configured: {ex}", file=sys.stderr)
                return 2
            if st.proposal is None:
                print("\n".join(st.errors), file=sys.stderr)
                return 3
            print(st.review_text)
            print(f"\nStored as {st.proposal.proposal_id}. Nothing has been committed.")
            return 0
        ledger = Ledger(app)
        if a.cmd == "show":
            prop, report = _reload(app, ledger, a.proposal_id, load_bundle(a.bundle))
            print(render_review(prop, report))
            return 0
        if a.cmd == "decide":
            bundle = load_bundle(a.bundle)
            prop, report = _reload(app, ledger, a.proposal_id, bundle)
            if a.decisions:
                decisions = decisions_from_json(json.loads(Path(a.decisions).read_text()), a.reviewer)
            else:
                ack = {x for x in a.ack.split(",") if x}
                decisions = [Decision(op, kind, a.reviewer, a.rationale, op in ack)
                             for kind, ops in (("accept", a.accept), ("reject", a.reject), ("defer", a.defer))
                             for op in ops.split(",") if op]
            try:
                res = apply_review(app, ledger, prop, report, decisions, bundle)
            except (ReviewError, NeedsRegeneration, RevisionConflict, ValidationError) as ex:
                print(f"not committed: {ex}", file=sys.stderr)
                return 4
            print(json.dumps({k: res[k] for k in ("proposal_id", "change_id", "rebased", "accepted", "rejected",
                                                  "deferred")}, indent=2))
            if res["commit"]:
                print(json.dumps({"required_actions": res["commit"]["required_actions"]}, indent=2))
            return 0
        if a.cmd == "challenge":
            loop = MaintenanceLoop(app)
            res = loop.challenge({"node_id": a.node, "aspect": a.aspect}, load_bundle(a.bundle))
            print(json.dumps({"domain": res["domain"]}, indent=2))
            st = res["steps"].get("scan")
            print(st.review_text if st else "No missing-dependency candidates found by the import scan.")
            return 0
        if a.cmd == "export-spec":
            Path(a.out).write_text(export_spec_markdown(app.graph(), ledger, a.title))
            print(f"wrote {a.out}")
            return 0
        if a.cmd == "ledger":
            for r in ledger.proposals():
                print(f"{r['id']} {r['status']} base r{r['base_graph_revision']} change {r['change_id']} "
                      f"ops {len(r['proposal']['operations'])}")
            for dd in ledger.decisions():
                print(f"  {dd['proposal_id']}/{dd['op_id']}: {dd['decision']} by {dd['reviewer']} {dd['rationale']!r}")
            return 0
    finally:
        app.close()
    return 1


if __name__ == "__main__":
    sys.exit(main())
